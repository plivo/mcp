package main

import (
	"fmt"
	"io"
	"strings"
)

func writeReview(w io.Writer, cat *Catalog, rv *Review) {
	p := func(format string, a ...any) { fmt.Fprintf(w, format, a...) }
	spend, destructive := 0, 0
	for _, o := range cat.Operations {
		if o.CostsMoney {
			spend++
		}
		if o.Destructive {
			destructive++
		}
	}
	p("# Catalog review\n\nGenerated by `catalog/gen`; do not edit by hand. Decisions live in `catalog/overrides.json`.\n\n")
	p("- Docs: %s (sha256 `%s`)\n- CLI: %s @ `%s`\n\n", cat.Sources.DocsURL, cat.Sources.DocsSHA256[:12], cat.Sources.CLIRepo, cat.Sources.CLICommit)
	p("| | count |\n|---|---|\n| Included operations | %d |\n| …costing money | %d |\n| …destructive (DELETE) | %d |\n| Excluded operations | %d |\n| CLI calls with no docs entry | %d |\n\n",
		len(cat.Operations), spend, destructive, len(cat.Excluded), len(rv.CLIOnly))

	p("## Included\n\n| id | module | $ | del | why |\n|---|---|---|---|---|\n")
	for _, r := range rv.Included {
		mod := r.op.Module
		if !existingModules[mod] {
			mod += " (new)"
		}
		p("| `%s` | %s | %s | %s | %s |\n", r.op.ID, mod, yes(r.op.CostsMoney), yes(r.op.Destructive), r.reason)
	}

	section(w, "Scope modules the auth proxy does not have yet", nil)
	for _, m := range sortedKeys(rv.NewModules) {
		p("- `%s`: %d ops\n", m, len(rv.NewModules[m]))
	}
	section(w, "Pricing to confirm (flagged as costing money until confirmed free)", rv.PricingCheck)
	section(w, "Param names that differ between docs and SDKs", rv.ParamDiffs)

	p("\n## Excluded\n\n| id | title | reason |\n|---|---|---|\n")
	for _, e := range rv.Excluded {
		p("| `%s` | %s | %s |\n", e.ID, e.Title, e.Reason)
	}
	section(w, "CLI calls with no docs entry (not in the catalog)", rv.CLIOnly)
	section(w, "CLI call sites resolved by hand or ignored", rv.Unresolved)
	var an []string
	for _, a := range rv.Anomalies {
		an = append(an, fmt.Sprintf("L%d %s", a.Line, a.Text))
	}
	section(w, "Docs text the parser skipped", an)
	section(w, "Endpoints documented more than once", rv.Duplicates)
}

func section(w io.Writer, title string, items []string) {
	fmt.Fprintf(w, "\n## %s\n\n", title)
	if items == nil {
		return
	}
	if len(items) == 0 {
		fmt.Fprint(w, "None.\n")
		return
	}
	for _, it := range items {
		fmt.Fprintf(w, "- %s\n", strings.ReplaceAll(it, "|", "\\|"))
	}
}

func yes(b bool) string {
	if b {
		return "yes"
	}
	return ""
}
